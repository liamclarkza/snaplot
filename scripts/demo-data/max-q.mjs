// `max-q`: the docs slice of the simulated launch the max-q page flies in the browser.
//
//   npm run demo-data -- max-q [--offline]
//
// Nothing is downloaded: the flight model (site/src/demos/max-q/flight.ts, run here with Node's
// type stripping) is deterministic. Writes site/src/examples/data/launch.ts: the telemetry every
// 4 s, the first stage's arc every 10 s and the flight events. SOURCE.md is written by hand.

import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { REPO, SLICES, biomeFormat, log, parseArgs, rel, round, writeOut } from './lib.mjs';

export const SLUG = 'max-q';
/** A made-up liftoff, for the slice's epoch-millisecond times. */
const LIFTOFF = Date.UTC(2026, 2, 14, 14, 30, 0);

async function main() {
  parseArgs();
  log(SLUG);
  const { fly } = await import(pathToFileURL(join(REPO, 'site/src/demos/max-q/flight.ts')).href);
  const flight = fly();
  const telemetry = flight.frames
    .filter((f) => Math.round(f.t * 10) % 40 === 0 || f === flight.frames.at(-1))
    .map((f) => ({
      t: round(f.t, 1),
      altitude: round(f.altitude, 2),
      speed: Math.round(f.velocity * 3.6),
      accel: round(f.accel, 2),
      q: round(f.q, 2),
      downrange: round(f.downrange, 1),
      stage: f.stage === 'stage 2' || f.stage === 'orbit' ? 'Stage 2' : 'Stage 1',
    }));
  const booster = flight.booster
    .filter((_, i) => i % 10 === 0 || i === flight.booster.length - 1)
    .map((b) => ({ t: b.t, altitude: round(b.altitude, 2), downrange: round(b.downrange, 1) }));
  const slicePath = join(SLICES, 'launch.ts');
  writeOut(
    slicePath,
    [
      '// Generated by `npm run demo-data -- max-q`; do not edit.',
      '// Source: the simulated two-stage launch of the max-q example (site/src/demos/max-q/flight.ts,',
      '// MIT); a model, not a real flight. SOURCE.md: site/public/data/max-q/.',
      '',
      '/** One telemetry frame, every 4 s from liftoff to second-stage shutdown. */',
      'export interface LaunchFrame {',
      '  /** Seconds since liftoff. */',
      '  t: number;',
      '  /** Kilometres up. */',
      '  altitude: number;',
      '  /** km/h. */',
      '  speed: number;',
      '  /** Sensed acceleration, g. */',
      '  accel: number;',
      '  /** Dynamic pressure, kPa. */',
      '  q: number;',
      '  /** Kilometres from the pad along the ground. */',
      '  downrange: number;',
      "  stage: 'Stage 1' | 'Stage 2';",
      '}',
      '',
      `export const telemetry: LaunchFrame[] = ${JSON.stringify(telemetry)};`,
      '',
      '/** The first stage after separation, every 10 s down its ballistic arc. */',
      'export interface BoosterPoint {',
      '  t: number;',
      '  altitude: number;',
      '  downrange: number;',
      '}',
      '',
      `export const booster: BoosterPoint[] = ${JSON.stringify(booster)};`,
      '',
      '/** The flight events, in seconds since liftoff. */',
      `export const events: { id: string; label: string; t: number }[] = ${JSON.stringify(flight.events)};`,
      '',
      '/** The (made-up) liftoff time, epoch milliseconds: 14 March 2026, 14:30 UTC. */',
      `export const LIFTOFF = ${LIFTOFF};`,
      '',
    ].join('\n'),
  );
  biomeFormat([slicePath]);
  log(`  wrote ${rel(slicePath)}`);
}

await main();
